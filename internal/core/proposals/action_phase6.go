// The Phase 6 actions (docs/design/phase-6-*.md). Their contracts are frozen
// here: types, Validate, Hash, Describe and the parsers all exist and are
// tested. A kind is turned on in Enabled together with its executor, so that
// ParseAction, ActionFromRow and Step refuse a kind that cannot run yet
// (ErrUnsupportedKind / RefuseUnsupported). All five are on now.
// ParseDefinedAction parses every defined kind regardless of Enabled, for tests
// and for the shell that builds an action from trusted server data.
//
// The Phase 6 publish action is named PublishRepo because Publish is already
// the hub command of this package.

// Limits of the Phase 6 actions.
const (
	// MaxIgnoreEntries and MaxIgnoreBytes bound one ignore proposal.
	MaxIgnoreEntries = 32
	MaxIgnoreBytes   = 4 << 10
	// MaxCommentSize bounds a review comment body.
	MaxCommentSize = 16 << 10
	// MaxInitContent bounds the README and the ignore file of a new repo.
	MaxInitContent = 64 << 10
	maxLeafLen     = 64
)

// Enabled reports whether proposals of the kind may be created and executed.
// A kind is on only when its executor exists, so a proposal that cannot run is
// never created (no false success). All Phase 6 kinds are on.
func Enabled(k core.ProposalKind) bool {
	switch k {
	case core.ProposalCommit, core.ProposalPush, core.ProposalMergeRequest,
		core.ProposalAgentFile, core.ProposalDeleteFiles, core.ProposalInstall,
		core.ProposalMergeLocal, core.ProposalRemoveWorktree,
		core.ProposalIgnoreEntries, core.ProposalReviewComment, core.ProposalPullFF,
		core.ProposalInitRepo, core.ProposalPublish:
		return true
	}
	return false
}

// defined reports whether the kind has a parseable action contract.
func defined(k core.ProposalKind) bool {
	if Enabled(k) {
		return true
	}
	switch k {
	case core.ProposalIgnoreEntries, core.ProposalReviewComment, core.ProposalInitRepo,
		core.ProposalPublish, core.ProposalPullFF:
		return true
	}
	return false
}

// IgnoreEntries appends exact entries to the .gitignore at the root of one
// repo's main checkout (WS-09). It cannot name another file. ExpectedAbsent says
// the file must not exist (it is then created exclusively); otherwise
// ExpectedHash is the hash of the whole current file, which must still match at
// execution. Existing text, line endings and unrelated entries are preserved by
// the executor. An absent file is not the hash of an empty one.
type IgnoreEntries struct {
	Where          Target
	Entries        []string
	ExpectedHash   string
	ExpectedAbsent bool
}

// ReviewComment posts one comment on a merge request (AC-02). ExpectedHead is
// the MR head the review was made against; a changed head refuses. Marker is
// generated by the shell before the proposal exists and is part of the posted
// text, so a lost reply can be reconciled by reading comments for it. Body,
// destination and marker are all in the hash and in Describe.
type ReviewComment struct {
	Repo         core.RepoID
	MRNumber     int
	ExpectedHead string
	Body         string
	Marker       string
}

// InitRepo initializes a reserved new repo (NR-01). It carries the immutable
// InitSpec fields, because this package cannot import core/newrepos; the
// shell converts and the hashes of the two are independent.
type InitRepo struct {
	Operation     core.OperationID
	Project       core.ProjectID
	Repo          core.RepoID
	Leaf          string
	Branch        string
	README        string
	Ignore        string
	CommitMessage string
}

// PublishRepo creates a remote on a host account, adds origin and pushes the
// first branch (NR-03/04). Private is the explicit default of the UI; the
// visibility is hash-covered and shown. Force cannot be expressed.
type PublishRepo struct {
	Operation    core.OperationID
	Repo         core.RepoID
	HostInstance string
	Owner        string
	OwnerKind    string
	Name         string
	Visibility   string
	Branch       string
	ExpectedHead string
	Marker       string
}

// PullFF fast-forwards the checked-out branch of a repo's main checkout from
// its upstream (AC-04). Merge, rebase and reset cannot be expressed: when the
// fast-forward is not possible nothing changes. Verify asks for the fast
// verification chain after a successful pull.
type PullFF struct {
	Repo       core.RepoID
	Branch     string
	Upstream   string
	ExpectHead string
	Verify     bool
}

func (IgnoreEntries) Kind() core.ProposalKind { return core.ProposalIgnoreEntries }
func (ReviewComment) Kind() core.ProposalKind { return core.ProposalReviewComment }
func (InitRepo) Kind() core.ProposalKind      { return core.ProposalInitRepo }
func (PublishRepo) Kind() core.ProposalKind   { return core.ProposalPublish }
func (PullFF) Kind() core.ProposalKind        { return core.ProposalPullFF }

func (IgnoreEntries) isAction() {}
func (ReviewComment) isAction() {}
func (InitRepo) isAction()      {}
func (PublishRepo) isAction()   {}
func (PullFF) isAction()        {}

// CheckIgnoreEntry validates one .gitignore line this package may add: an
// anchored directory entry written as "/dir/" or "/a/b/", with every
// gitignore metacharacter (* ? [ ] ! # and a leading space) escaped by a
// backslash, no control character, no ".." or "." part and no drive or stream
// marker. A bare "*", a source directory pattern with no slash anchor, a
// comment, a negation and an absolute path are all refused.
func CheckIgnoreEntry(e string) error {
	if len(e) < 3 || len(e) > 512 || !utf8.ValidString(e) || hasControl(e) {
		return invalid("an ignore entry is empty, too long or has control characters")
	}
	if e[0] != '/' || e[len(e)-1] != '/' {
		return invalid("ignore entry %q must be an anchored folder such as /build/", e)
	}
	body := e[1 : len(e)-1]
	var plain strings.Builder
	esc := false
	for _, r := range body {
		switch {
		case esc:
			plain.WriteRune(r)
			esc = false
		case r == '\\':
			esc = true
		case strings.ContainsRune("*?[]!#", r):
			return invalid("ignore entry %q has an unescaped pattern character", e)
		default:
			plain.WriteRune(r)
		}
	}
	if esc {
		return invalid("ignore entry %q ends in a lone backslash", e)
	}
	p := plain.String()
	if p == "" || strings.ContainsAny(p, `:<>"|`) {
		return invalid("ignore entry %q has a character Windows does not allow", e)
	}
	for _, seg := range strings.Split(p, "/") {
		if seg == "" || seg == "." || seg == ".." || strings.EqualFold(seg, ".git") ||
			strings.HasSuffix(seg, ".") || strings.HasSuffix(seg, " ") || strings.HasPrefix(seg, " ") {
			return invalid("ignore entry %q has an empty, relative or reserved part", e)
		}
	}
	return nil
}

func (a IgnoreEntries) Validate() error {
	m, ok := a.Where.(MainCheckout)
	if !ok {
		return invalid("an ignore change acts in the main checkout of a repo")
	}
	if m.Repo.Validate() != nil {
		return invalid("the repo id is not valid")
	}
	if n := len(a.Entries); n == 0 || n > MaxIgnoreEntries {
		return invalid("choose between 1 and %d ignore entries", MaxIgnoreEntries)
	}
	total := 0
	seen := map[string]bool{}
	for _, e := range a.Entries {
		if err := CheckIgnoreEntry(e); err != nil {
			return err
		}
		if seen[e] {
			return invalid("ignore entry %q is listed twice", e)
		}
		seen[e] = true
		total += len(e) + 1
	}
	if total > MaxIgnoreBytes {
		return invalid("the ignore entries are over %d KiB", MaxIgnoreBytes>>10)
	}
	switch {
	case a.ExpectedAbsent && a.ExpectedHash != "":
		return invalid("a file that must be absent has no checksum")
	case !a.ExpectedAbsent:
		if len(a.ExpectedHash) != 64 || !isHex(a.ExpectedHash) {
			return invalid("expected_hash must be a 64-digit lowercase hex checksum")
		}
	}
	return nil
}

// checkMarker accepts a lowercase hex marker of 16 to 64 digits.
func checkMarker(m string) error {
	if len(m) < 16 || len(m) > 64 || !isHex(m) {
		return invalid("the operation marker must be 16 to 64 lowercase hex digits")
	}
	return nil
}

func checkFullHead(name, v string) error {
	if (len(v) != 40 && len(v) != 64) || !isHex(v) {
		return invalid("%s must be a full lowercase hex commit ID", name)
	}
	return nil
}

func (a ReviewComment) Validate() error {
	if a.Repo.Validate() != nil {
		return invalid("the repo id is not valid")
	}
	if a.MRNumber <= 0 {
		return invalid("the merge request number must be positive")
	}
	if err := checkFullHead("expect_head", a.ExpectedHead); err != nil {
		return err
	}
	switch {
	case strings.TrimSpace(a.Body) == "":
		return invalid("the comment is empty")
	case len(a.Body) > MaxCommentSize:
		return invalid("the comment is over %d KiB", MaxCommentSize>>10)
	case !utf8.ValidString(a.Body):
		return invalid("the comment is not valid text")
	}
	for _, r := range a.Body {
		if (r < 0x20 && r != '\n' && r != '\t' && r != '\r') || r == 0x7f {
			return invalid("the comment has control characters")
		}
	}
	return checkMarker(a.Marker)
}

func (a InitRepo) Validate() error {
	if a.Operation.Validate() != nil || a.Project.Validate() != nil || a.Repo.Validate() != nil {
		return invalid("the operation, project or repo id is not valid")
	}
	if len(a.Leaf) > maxLeafLen || strings.Contains(a.Leaf, "/") {
		return invalid("the folder name must be one name of at most %d characters", maxLeafLen)
	}
	if err := CheckRelPath(a.Leaf); err != nil {
		return err
	}
	if a.Branch != "main" {
		return invalid("the first branch of a new repo is main")
	}
	for _, c := range []string{a.README, a.Ignore} {
		if len(c) > MaxInitContent || !utf8.ValidString(c) || strings.ContainsRune(c, 0) {
			return invalid("a file's content is over %d KiB or is not text", MaxInitContent>>10)
		}
	}
	return checkMessage(a.CommitMessage)
}

func checkAccount(what, v string) error {
	if v == "" || len(v) > 100 || v[0] == '.' || v[0] == '-' || strings.HasSuffix(v, ".git") {
		return invalid("the %s is not valid", what)
	}
	for _, r := range v {
		ok := r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.'
		if !ok {
			return invalid("the %s may only hold letters, digits, - _ and .", what)
		}
	}
	return nil
}

func (a PublishRepo) Validate() error {
	if a.Operation.Validate() != nil || a.Repo.Validate() != nil {
		return invalid("the operation or repo id is not valid")
	}
	if core.ValidateHostInstance(a.HostInstance) != nil {
		return invalid("the host is not valid")
	}
	if err := checkAccount("owner", a.Owner); err != nil {
		return err
	}
	if err := checkAccount("repository name", a.Name); err != nil {
		return err
	}
	if a.OwnerKind != "user" && a.OwnerKind != "org" {
		return invalid("say whether the owner is a user or an organization")
	}
	if a.Visibility != "private" && a.Visibility != "public" {
		return invalid("choose private or public")
	}
	if a.Branch != "main" {
		return invalid("only the main branch is published")
	}
	if err := checkFullHead("expect_head", a.ExpectedHead); err != nil {
		return err
	}
	return checkMarker(a.Marker)
}

func (a PullFF) Validate() error {
	if a.Repo.Validate() != nil {
		return invalid("the repo id is not valid")
	}
	if err := CheckBranch(a.Branch); err != nil {
		return err
	}
	// Upstream is "<remote>/<branch>".
	remote, branch, ok := strings.Cut(a.Upstream, "/")
	if !ok {
		return invalid("the upstream must look like origin/main")
	}
	if err := CheckRemoteName(remote); err != nil {
		return err
	}
	if err := CheckBranch(branch); err != nil {
		return err
	}
	return checkFullHead("expect_head", a.ExpectHead)
}

// Wire shapes of the Phase 6 actions; as for the older kinds they are both the
// arguments and the stored payload.
type (
	ignoreArgs struct {
		Repo           string   `json:"repo"`
		Entries        []string `json:"entries"`
		ExpectedHash   string   `json:"expected_hash,omitempty"`
		ExpectedAbsent bool     `json:"expected_absent,omitempty"`
	}
	commentArgs struct {
		Repo         string `json:"repo"`
		MRNumber     int    `json:"mr_number"`
		ExpectedHead string `json:"expect_head"`
		Body         string `json:"body"`
		Marker       string `json:"marker"`
	}
	initArgs struct {
		Operation     string `json:"operation"`
		Project       string `json:"project"`
		Repo          string `json:"repo"`
		Leaf          string `json:"leaf"`
		Branch        string `json:"branch"`
		README        string `json:"readme"`
		Ignore        string `json:"ignore"`
		CommitMessage string `json:"commit_message"`
	}
	publishArgs struct {
		Operation    string `json:"operation"`
		Repo         string `json:"repo"`
		HostInstance string `json:"host"`
		Owner        string `json:"owner"`
		OwnerKind    string `json:"owner_kind"`
		Name         string `json:"name"`
		Visibility   string `json:"visibility"`
		Branch       string `json:"branch"`
		ExpectedHead string `json:"expect_head"`
		Marker       string `json:"marker"`
	}
	pullArgs struct {
		Repo       string `json:"repo"`
		Branch     string `json:"branch"`
		Upstream   string `json:"upstream"`
		ExpectHead string `json:"expect_head"`
		Verify     bool   `json:"verify,omitempty"`
	}
)

// parsePhase6 builds the action of a Phase 6 kind from its strict JSON shape.
func parsePhase6(k core.ProposalKind, data []byte) (Action, error) {
	var a Action
	switch k {
	case core.ProposalIgnoreEntries:
		var v ignoreArgs
		if err := decodeStrict(data, &v); err != nil {
			return nil, err
		}
		a = IgnoreEntries{Where: MainCheckout{Repo: core.RepoID(v.Repo)}, Entries: v.Entries, ExpectedHash: v.ExpectedHash, ExpectedAbsent: v.ExpectedAbsent}
	case core.ProposalReviewComment:
		var v commentArgs
		if err := decodeStrict(data, &v); err != nil {
			return nil, err
		}
		a = ReviewComment{Repo: core.RepoID(v.Repo), MRNumber: v.MRNumber, ExpectedHead: v.ExpectedHead, Body: v.Body, Marker: v.Marker}
	case core.ProposalInitRepo:
		var v initArgs
		if err := decodeStrict(data, &v); err != nil {
			return nil, err
		}
		a = InitRepo{Operation: core.OperationID(v.Operation), Project: core.ProjectID(v.Project), Repo: core.RepoID(v.Repo),
			Leaf: v.Leaf, Branch: v.Branch, README: v.README, Ignore: v.Ignore, CommitMessage: v.CommitMessage}
	case core.ProposalPublish:
		var v publishArgs
		if err := decodeStrict(data, &v); err != nil {
			return nil, err
		}
		a = PublishRepo{Operation: core.OperationID(v.Operation), Repo: core.RepoID(v.Repo), HostInstance: v.HostInstance,
			Owner: v.Owner, OwnerKind: v.OwnerKind, Name: v.Name, Visibility: v.Visibility, Branch: v.Branch,
			ExpectedHead: v.ExpectedHead, Marker: v.Marker}
	case core.ProposalPullFF:
		var v pullArgs
		if err := decodeStrict(data, &v); err != nil {
			return nil, err
		}
		a = PullFF{Repo: core.RepoID(v.Repo), Branch: v.Branch, Upstream: v.Upstream, ExpectHead: v.ExpectHead, Verify: v.Verify}
	default:
		return nil, fmt.Errorf("%w: %q", ErrUnsupportedKind, string(k))
	}
	if err := a.Validate(); err != nil {
		return nil, err
	}
	return a, nil
}

// ParseDefinedAction parses any kind with a frozen contract, including those
// Enabled reports false for. It is not a creation path: Step still refuses an
// action whose kind is not Enabled. Use it in tests and in shell code that
// builds an action from trusted server data.
func ParseDefinedAction(kind string, data []byte) (Action, error) {
	k := core.ProposalKind(kind)
	if k.Validate() != nil || !defined(k) {
		return nil, fmt.Errorf("%w: %q", ErrUnsupportedKind, kind)
	}
	if Enabled(k) {
		return ParseAction(kind, data)
	}
	a, err := parsePhase6(k, data)
	return a, wrapKind(kind, err)
}

// phase6RowOf is RowOf for the Phase 6 actions.
func phase6RowOf(a Action) (core.ProposalKind, []byte, bool) {
	var v any
	switch x := a.(type) {
	case IgnoreEntries:
		_, r := targetArgs(x.Where)
		v = ignoreArgs{r, x.Entries, x.ExpectedHash, x.ExpectedAbsent}
	case ReviewComment:
		v = commentArgs{string(x.Repo), x.MRNumber, x.ExpectedHead, x.Body, x.Marker}
	case InitRepo:
		v = initArgs{string(x.Operation), string(x.Project), string(x.Repo), x.Leaf, x.Branch, x.README, x.Ignore, x.CommitMessage}
	case PublishRepo:
		v = publishArgs{string(x.Operation), string(x.Repo), x.HostInstance, x.Owner, x.OwnerKind, x.Name, x.Visibility, x.Branch, x.ExpectedHead, x.Marker}
	case PullFF:
		v = pullArgs{string(x.Repo), x.Branch, x.Upstream, x.ExpectHead, x.Verify}
	default:
		return "", nil, false
	}
	b, err := json.Marshal(v)
	if err != nil { // plain strings, ints and slices cannot fail to marshal
		return a.Kind(), nil, true
	}
	return a.Kind(), b, true
}

// canonicalPhase6 writes the hash input of a Phase 6 action.
func canonicalPhase6(c *canon, a Action) {
	switch v := a.(type) {
	case IgnoreEntries:
		c.target(v.Where)
		c.s(fmt.Sprint(len(v.Entries)))
		for _, e := range v.Entries {
			c.s(e)
		}
		c.s(v.ExpectedHash)
		if v.ExpectedAbsent {
			c.s("absent")
		} else {
			c.s("present")
		}
	case ReviewComment:
		c.s(string(v.Repo))
		c.s(fmt.Sprint(v.MRNumber))
		c.s(v.ExpectedHead)
		c.s(v.Body)
		c.s(v.Marker)
	case InitRepo:
		c.s(string(v.Operation))
		c.s(string(v.Project))
		c.s(string(v.Repo))
		c.s(v.Leaf)
		c.s(v.Branch)
		c.s(v.README)
		c.s(v.Ignore)
		c.s(v.CommitMessage)
	case PublishRepo:
		c.s(string(v.Operation))
		c.s(string(v.Repo))
		c.s(v.HostInstance)
		c.s(v.Owner)
		c.s(v.OwnerKind)
		c.s(v.Name)
		c.s(v.Visibility)
		c.s(v.Branch)
		c.s(v.ExpectedHead)
		c.s(v.Marker)
	case PullFF:
		c.s(string(v.Repo))
		c.s(v.Branch)
		c.s(v.Upstream)
		c.s(v.ExpectHead)
		if v.Verify {
			c.s("verify")
		} else {
			c.s("no-verify")
		}
	}
}

// describePhase6 is the confirmation text of a Phase 6 action: the exact
// destination, content and expected state.
func describePhase6(a Action) ([]Line, bool) {
	var out []Line
	add := func(f string, args ...any) { out = append(out, Line{Text: fmt.Sprintf(f, args...)}) }
	switch v := a.(type) {
	case IgnoreEntries:
		add("Add %s to .gitignore in %s.", plural(len(v.Entries), "entry", "entries"), describeTarget(v.Where))
		for _, e := range v.Entries {
			out = append(out, Line{Text: "  " + e})
		}
		if v.ExpectedAbsent {
			add("The .gitignore does not exist yet; it will be created.")
		} else {
			add("Only these entries are added after the existing text. The file is changed only if it still has checksum %s.", v.ExpectedHash)
		}
		add("No file is deleted, and no other file is touched.")
	case ReviewComment:
		add("Post a comment on merge request !%d of repo %s.", v.MRNumber, v.Repo)
		add("It is posted only if the merge request still points at %s.", v.ExpectedHead)
		add("Comment (%s), ending with marker %s:", plural(len(v.Body), "byte", "bytes"), v.Marker)
		out = append(out, Line{Text: v.Body})
		add("This writes to the git host as your account.")
	case InitRepo:
		add("Create the new repo folder %q in project %s and initialize it.", v.Leaf, v.Project)
		add("Steps: create the folder, run git init (branch %s), write README.md, write .gitignore, make the first commit, then track the repo.", v.Branch)
		add("Commit message: %s", v.CommitMessage)
		add("README.md (%s):", plural(len(v.README), "byte", "bytes"))
		out = append(out, Line{Text: v.README})
		add(".gitignore (%s):", plural(len(v.Ignore), "byte", "bytes"))
		out = append(out, Line{Text: v.Ignore})
		add("The folder must not exist yet. Nothing is overwritten or deleted.")
	case PublishRepo:
		add("Create the %s repository %s/%s on %s (an %s account) and push %s to it.", v.Visibility, v.Owner, v.Name, v.HostInstance, v.OwnerKind, v.Branch)
		add("The first commit %s is pushed with a normal, never forced, push. An existing origin is never replaced.", v.ExpectedHead)
		add("The repository description carries the marker %s so an interrupted request can be checked.", v.Marker)
		if v.Visibility == "public" {
			add("PUBLIC: anyone can see this repository.")
		}
	case PullFF:
		add("Fast-forward branch %s of the main checkout of repo %s from %s.", v.Branch, v.Repo, v.Upstream)
		add("Only a fast-forward is done. If the branch has diverged, local changes would be overwritten or the checkout is not clean, nothing changes.")
		add("Expected branch tip: %s.", v.ExpectHead)
		if v.Verify {
			add("After a successful pull, the fast verification checks run.")
		}
	default:
		return nil, false
	}
	return out, true
}
