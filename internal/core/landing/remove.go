// MaxHolders caps the process names a lock message carries.
const MaxHolders = 5

// RemoveReq comes from the worktree row (never from a request body).
type RemoveReq struct {
	Worktree core.WorktreeID
	Repo     core.RepoID
	Path     string
	Branch   string
	// Root is the worktree root; Name the worktree's folder name.
	Root string
	Name string
	// StagedLeaf is the staged folder leaf the row remembers from an earlier
	// attempt ("" on a first attempt). It is the only staged folder this
	// removal may resume: no other folder is ever matched by name.
	StagedLeaf string
}

// validStagedLeaf reports whether a leaf could have been made by StagingPath.
func validStagedLeaf(leaf string) bool {
	if leaf == "" || len(leaf) > 200 || leaf[0] == '.' {
		return false
	}
	return strings.Trim(leaf, "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_-.") == ""
}

// Validate checks the IDs and the non-empty strings.
func (r RemoveReq) Validate() error {
	if r.Path == "" || r.Root == "" || r.Name == "" {
		return errors.New("a removal needs a path, a root and a name")
	}
	if r.StagedLeaf != "" && !validStagedLeaf(r.StagedLeaf) {
		return errors.New("the remembered staged folder name is not valid")
	}
	return errors.Join(r.Worktree.Validate(), r.Repo.Validate())
}

// RemoveRefuse says why a removal was refused before anything was touched.
type RemoveRefuse string

const (
	RemoveOutsideRoot  RemoveRefuse = "outside_root"
	RemoveMainCheckout RemoveRefuse = "main_checkout"
	RemoveTaskRunning  RemoveRefuse = "task_running"
	RemoveInUse        RemoveRefuse = "in_use"
	RemoveDirty        RemoveRefuse = "dirty"
	RemoveUnreadable   RemoveRefuse = "unreadable"
)

// Validate reports whether r is known.
func (r RemoveRefuse) Validate() error {
	switch r {
	case RemoveOutsideRoot, RemoveMainCheckout, RemoveTaskRunning, RemoveInUse, RemoveDirty, RemoveUnreadable:
		return nil
	}
	return fmt.Errorf("unknown removal refusal %q", string(r))
}

// LockClass is what kind of file lock stopped a move or delete.
type LockClass string

const (
	LockSharing      LockClass = "sharing"
	LockAccessDenied LockClass = "access_denied"
	LockPathTooLong  LockClass = "path_too_long"
	LockOther        LockClass = "other"
)

// Validate reports whether c is known; the empty class is invalid (R7).
func (c LockClass) Validate() error {
	switch c {
	case LockSharing, LockAccessDenied, LockPathTooLong, LockOther:
		return nil
	}
	return fmt.Errorf("unknown lock class %q", string(c))
}

// RemoveState is the state of one removal run (sealed).
type RemoveState interface{ isRemoveState() }

// RemoveIdle: not started.
type RemoveIdle struct{}

// RemoveChecking: waiting for RemoveObserved. Planned is the staging path
// derived at the start; it is used if the move goes ahead.
type RemoveChecking struct {
	Req     RemoveReq
	Planned StagePath
}

// Moving: MoveToStaging was emitted.
type Moving struct {
	Req    RemoveReq
	Staged StagePath
	// OtherPrunable was true at observation: do not prune (R5).
	OtherPrunable bool
}

// Deleting: DeleteStaged was emitted.
type Deleting struct {
	Req    RemoveReq
	Staged StagePath
	// OtherPrunable was true at observation: do not prune (R5).
	OtherPrunable bool
}

// Pruning: PruneWorktrees was emitted.
type Pruning struct{ Req RemoveReq }

// Removed: terminal; Note says if prune was skipped.
type Removed struct{ Note string }

// RemoveRefused: terminal; nothing was touched.
type RemoveRefused struct{ Reason RemoveRefuse }

// Locked: terminal; the rename failed and nothing changed. Retryable.
type Locked struct {
	Class   LockClass
	Holders []string
}

// Stuck: terminal; the rename worked but the delete is incomplete. Retryable.
type Stuck struct {
	Staged    StagePath
	Class     LockClass
	Holders   []string
	Remaining int
}

// RemoveFailed: terminal.
type RemoveFailed struct {
	Reason    string
	Retryable bool
}

func (RemoveIdle) isRemoveState()     {}
func (RemoveChecking) isRemoveState() {}
func (Moving) isRemoveState()         {}
func (Deleting) isRemoveState()       {}
func (Pruning) isRemoveState()        {}
func (Removed) isRemoveState()        {}
func (RemoveRefused) isRemoveState()  {}
func (Locked) isRemoveState()         {}
func (Stuck) isRemoveState()          {}
func (RemoveFailed) isRemoveState()   {}

// RemoveInput is one event for StepRemove (sealed).
type RemoveInput interface{ isRemoveInput() }

// RemoveStart begins a run. StageID is generated by the shell and feeds
// StagingPath.
type RemoveStart struct {
	Req     RemoveReq
	StageID string
	Now     time.Time
}

// RemoveObserved is the result of ObserveWorktree.
type RemoveObserved struct {
	UnderRoot      bool
	IsMain         bool
	RowStatus      core.WorktreeStatus
	PathExists     bool
	StagedExists   bool
	Staged         StagePath
	Clean          bool
	StatusReadable bool
	TaskLive       bool
	BuildLive      bool
	OtherPrunable  bool
	Now            time.Time
}

// Moved: the rename worked.
type Moved struct{ Now time.Time }

// MoveFailed: the rename failed; nothing changed.
type MoveFailed struct {
	Class   LockClass
	Holders []string
	Now     time.Time
}

// Deleted: the staged folder is gone.
type Deleted struct{ Now time.Time }

// DeleteFailed: the delete is incomplete.
type DeleteFailed struct {
	Class     LockClass
	Holders   []string
	Remaining int
	Now       time.Time
}

// Pruned: git worktree prune worked.
type Pruned struct{ Now time.Time }

// PruneFailed: git worktree prune failed.
type PruneFailed struct {
	Msg string
	Now time.Time
}

func (RemoveStart) isRemoveInput()    {}
func (RemoveObserved) isRemoveInput() {}
func (Moved) isRemoveInput()          {}
func (MoveFailed) isRemoveInput()     {}
func (Deleted) isRemoveInput()        {}
func (DeleteFailed) isRemoveInput()   {}
func (Pruned) isRemoveInput()         {}
func (PruneFailed) isRemoveInput()    {}

// RemoveCommand is plain data that asks the shell for an effect (sealed). The
// set is closed on purpose (R6): no branch, force or delete-by-path command;
// DeleteStaged carries a StagePath, never an arbitrary path.
type RemoveCommand interface{ isRemoveCommand() }

// ObserveWorktree reads the facts for RemoveObserved. Read only.
type ObserveWorktree struct{ Req RemoveReq }

// MoveToStaging renames the worktree folder into the staging folder.
type MoveToStaging struct {
	Req RemoveReq
	To  StagePath
}

// MarkRemoving moves the worktree row to removing, remembering the staged
// leaf. Idempotent (monotone, expected-status update).
type MarkRemoving struct {
	Worktree core.WorktreeID
	Staged   StagePath
}

// DeleteStaged deletes the staged folder (platform.RemoveStaged). Idempotent;
// a missing folder is success.
type DeleteStaged struct{ Staged StagePath }

// PruneWorktrees runs git worktree prune for the repo. Idempotent.
type PruneWorktrees struct{ Repo core.RepoID }

// MarkRemoved moves the worktree row to removed. Idempotent.
type MarkRemoved struct{ Worktree core.WorktreeID }

func (ObserveWorktree) isRemoveCommand() {}
func (MoveToStaging) isRemoveCommand()   {}
func (MarkRemoving) isRemoveCommand()    {}
func (DeleteStaged) isRemoveCommand()    {}
func (PruneWorktrees) isRemoveCommand()  {}
func (MarkRemoved) isRemoveCommand()     {}

// WriteAudit is shared with the merge set: one audit entry per terminal outcome.
func (WriteAudit) isRemoveCommand() {}
