// DTOs of the Phase 6 areas: workspace actions, host context, draft tasks,
// noise, notifications, standup and new repos (docs/design/phase-6-*.md).
// They are plain Go structs with JSON tags; `task generate` turns them into
// web/src/api/gen/api.gen.ts, so a changed field breaks the frontend build, not
// a request at runtime (docs/AGENTS.md 5.8). Rules shared by all of them:
//
//   - IDs are tracked IDs; the server resolves the host instance, project,
//     path and object. No request carries a host URL or a filesystem path.
//   - Text from a host, a log or an agent is plain text, never HTML.
//   - Nothing here can hold a token or credential URL.
//   - String-typed enums are closed sets; internal/api's contract test checks
//     that they match the core packages they mirror.

// Topics added in Phase 6. Each carries the message type named. A client that
// sees a gap (Seq jump or MsgGap) refetches the named query; it never replays
// old browser toasts (docs/design/phase-6-notifications.md).
const (
	// TopicNotices carries NoticeChangedMessage: a notice was committed. The
	// client invalidates its notification history query.
	TopicNotices = "notices"
	// TopicActions carries ActionChangedMessage: a workspace action request
	// changed state.
	TopicActions = "actions"
	// TopicNewRepos carries NewRepoChangedMessage: a new-repo operation changed
	// state or advanced a stage.
	TopicNewRepos = "newrepos"
)

// Workspace actions (AC-01 to AC-06).

// ActionKind is a typed action of the server catalogue.
type ActionKind string

const (
	ActionDiagnosePipeline ActionKind = "diagnose_pipeline"
	ActionFixPipeline      ActionKind = "fix_pipeline"
	ActionReviewMR         ActionKind = "review_mr"
	ActionProposeCommits   ActionKind = "propose_commits"
	ActionPullAndCheck     ActionKind = "pull_and_check"
	ActionImportIssue      ActionKind = "import_issue"
	ActionDiagnoseBuild    ActionKind = "diagnose_build"
	ActionDiagnoseRepo     ActionKind = "diagnose_repo"
	ActionProposeIgnore    ActionKind = "propose_ignore"
)

// AttentionReason is one reason a repo is in "Needs attention".
type AttentionReason string

const (
	ReasonUnreadable  AttentionReason = "unreadable"
	ReasonConflicts   AttentionReason = "conflicts"
	ReasonDiverged    AttentionReason = "diverged"
	ReasonFailedCI    AttentionReason = "failed_ci"
	ReasonFailedBuild AttentionReason = "failed_build"
	ReasonBehind      AttentionReason = "behind"
	ReasonDirty       AttentionReason = "dirty"
)

// ActionContextAvailability says whether an offering's source context can be
// read. "metadata_only" means the action is still offered and runs with
// tracked facts only; the Note explains what is missing.
type ActionContextAvailability string

const (
	ContextAvailable    ActionContextAvailability = "available"
	ContextMetadataOnly ActionContextAvailability = "metadata_only"
	ContextNone         ActionContextAvailability = "none"
)

// ActionOfferingDTO is one entry of a repo's action catalogue. Mode is empty
// for a kind that starts no agent turn (a draft import, a pull proposal).
type ActionOfferingDTO struct {
	Kind    ActionKind                `json:"kind"`
	Reason  AttentionReason           `json:"reason"`
	Title   string                    `json:"title"`
	Mode    core.TaskMode             `json:"mode,omitempty"`
	Context ActionContextAvailability `json:"context"`
	// SourceID pins the object the action acts on (CI run, MR number, build
	// ID); empty when the kind has none.
	SourceID string `json:"sourceId,omitempty"`
	// WaitingForFolder: the repo cannot be read, so a started task would wait
	// for a restored folder. The UI says so and never shows it as running.
	WaitingForFolder bool   `json:"waitingForFolder,omitempty"`
	Note             string `json:"note,omitempty"`
}

// ActionCatalogueResponse is the body of GET /api/repos/{id}/actions.
type ActionCatalogueResponse struct {
	RepoID    core.RepoID         `json:"repoId"`
	Offerings []ActionOfferingDTO `json:"offerings"`
}

// ActionRequestDTO is the body of POST /api/actions/preview and the identity
// part of the execute body. RequestID is generated by the browser once per
// submission. SourceID is a plain ID the catalogue offered, never a URL.
type ActionRequestDTO struct {
	RequestID core.RequestID `json:"requestId"`
	RepoID    core.RepoID    `json:"repoId"`
	Kind      ActionKind     `json:"kind"`
	SourceID  string         `json:"sourceId,omitempty"`
	Agent     string         `json:"agent,omitempty"`
	Model     string         `json:"model,omitempty"`
}

// ActionPreviewDTO is the body of POST /api/actions/preview: what the action
// would attach and do, before anything starts. Digest binds the later execute.
type ActionPreviewDTO struct {
	RequestID core.RequestID `json:"requestId"`
	Digest    string         `json:"digest"`
	Kind      ActionKind     `json:"kind"`
	Mode      core.TaskMode  `json:"mode,omitempty"`
	// Source labels where the context came from.
	Source string `json:"source"`
	// ContextText is the bounded, redacted text that will be attached.
	ContextText string `json:"contextText"`
	Truncated   bool   `json:"truncated,omitempty"`
	// Unavailable lists labelled gaps (no token, expired log, unreadable folder).
	Unavailable      []string                  `json:"unavailable,omitempty"`
	Context          ActionContextAvailability `json:"context"`
	WaitingForFolder bool                      `json:"waitingForFolder,omitempty"`
	// ExpectedHead pins the repo HEAD the preview was made against.
	ExpectedHead string `json:"expectedHead,omitempty"`
}

// ActionExecuteRequest is the body of POST /api/actions/execute. Digest and
// ExpectedHead are copied from the preview; a changed scope refuses.
type ActionExecuteRequest struct {
	ActionRequestDTO
	Digest       string `json:"digest"`
	ExpectedHead string `json:"expectedHead,omitempty"`
}

// ActionRequestState is the stored state of a request.
type ActionRequestState string

const (
	ActionStateSubmitting ActionRequestState = "submitting"
	ActionStateCompleted  ActionRequestState = "completed"
	ActionStateRefused    ActionRequestState = "refused"
	ActionStateCancelled  ActionRequestState = "cancelled"
)

// ActionResultDTO is the body of POST /api/actions/execute and
// GET /api/actions/{requestId}. For an import TaskID is a DRAFT task; moving a
// draft to the queue is a separate, explicit start. Message says plainly what
// happened, or why it was refused.
type ActionResultDTO struct {
	RequestID   core.RequestID     `json:"requestId"`
	State       ActionRequestState `json:"state"`
	TaskID      core.TaskID        `json:"taskId,omitempty"`
	ProposalIDs []core.ProposalID  `json:"proposalIds,omitempty"`
	BatchID     string             `json:"batchId,omitempty"`
	// Refusal is the stable reason code of a refused request.
	Refusal string `json:"refusal,omitempty"`
	Message string `json:"message"`
}

// ActionChangedMessage is the data of a message on TopicActions. It carries no
// prompt or context.
type ActionChangedMessage struct {
	RequestID core.RequestID     `json:"requestId"`
	State     ActionRequestState `json:"state"`
}

// Host context (GH-05, GH-06).

// HostContextPhase is where a host context read stands.
type HostContextPhase string

const (
	HostContextReady   HostContextPhase = "ready"
	HostContextPartial HostContextPhase = "partial"
	HostContextWaiting HostContextPhase = "waiting"
	HostContextBlocked HostContextPhase = "blocked"
)

// HostContextReason says why a read is blocked or a part is missing.
type HostContextReason string

const (
	HostContextNoToken        HostContextReason = "no_token"
	HostContextForbidden      HostContextReason = "forbidden"
	HostContextNotFound       HostContextReason = "not_found"
	HostContextUnsupported    HostContextReason = "unsupported"
	HostContextRetryExhausted HostContextReason = "retry_exhausted"
	HostContextUntracked      HostContextReason = "untracked"
	HostContextTooLarge       HostContextReason = "too_large"
)

// HostContextStatusDTO is the shared status of every host context response.
// A blocked or partial read is a normal answer with a plain Message, not an
// error status.
type HostContextStatusDTO struct {
	Phase       HostContextPhase            `json:"phase"`
	Reason      HostContextReason           `json:"reason,omitempty"`
	Unavailable []HostContextUnavailableDTO `json:"unavailable,omitempty"`
	// RetryAt is set while waiting for a retry.
	RetryAt   *time.Time `json:"retryAt,omitempty"`
	ExpiresAt *time.Time `json:"expiresAt,omitempty"`
	Message   string     `json:"message,omitempty"`
}

// HostContextUnavailableDTO labels one missing part of a partial result.
type HostContextUnavailableDTO struct {
	Source string            `json:"source"`
	Reason HostContextReason `json:"reason"`
}

// FailedJobDTO is one failed CI job. Log is redacted plain text, at most 256
// KiB; LogUnavailable names why it is absent.
type FailedJobDTO struct {
	JobID          string `json:"jobId"`
	Name           string `json:"name"`
	Stage          string `json:"stage,omitempty"`
	Log            string `json:"log,omitempty"`
	LogTruncated   bool   `json:"logTruncated,omitempty"`
	LogUnavailable string `json:"logUnavailable,omitempty"`
}

// FailedJobsResponse is the body of GET /api/repos/{id}/ci/runs/{runId}/failed-jobs.
type FailedJobsResponse struct {
	RepoID    core.RepoID          `json:"repoId"`
	RunID     string               `json:"runId"`
	Head      string               `json:"head,omitempty"`
	Jobs      []FailedJobDTO       `json:"jobs"`
	Truncated bool                 `json:"truncated,omitempty"`
	Status    HostContextStatusDTO `json:"status"`
}

// IssueDTO is one issue in a list or detail. Body is plain text.
