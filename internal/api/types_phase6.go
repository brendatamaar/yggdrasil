// Noise (WS-09).

// NoiseEvidenceDTO says what a suggestion is based on.
type NoiseEvidenceDTO struct {
	Total          int `json:"total"`
	Sampled        int `json:"sampled"`
	UnderDirectory int `json:"underDirectory"`
}

// NoiseCandidateDTO is one suggested ignore entry.
type NoiseCandidateDTO struct {
	Directory   string           `json:"directory"`
	Pattern     string           `json:"pattern"`
	SampleCount int              `json:"sampleCount"`
	Evidence    NoiseEvidenceDTO `json:"evidence"`
	// Incomplete: the sample was truncated, so this is based on a sample.
	Incomplete bool `json:"incomplete,omitempty"`
}

// NoiseResponse is the body of GET /api/repos/{id}/noise. Available is false
// when the repo could not be read; that is labelled, not an empty success.
type NoiseResponse struct {
	RepoID     core.RepoID         `json:"repoId"`
	Available  bool                `json:"available"`
	Candidates []NoiseCandidateDTO `json:"candidates"`
	// PendingProposalID is set while an ignore proposal awaits confirmation.
	PendingProposalID core.ProposalID `json:"pendingProposalId,omitempty"`
	Message           string          `json:"message,omitempty"`
}

// CreateIgnoreProposalRequest is the body of POST /api/repos/{id}/noise/proposals:
// a nonempty subset (at most 32 entries) of the current candidates' patterns.
// The server reads the current .gitignore hash itself; the result is an
// ordinary pending proposal (ProposalDTO), confirmed through the proposals API.
type CreateIgnoreProposalRequest struct {
	RequestID core.RequestID `json:"requestId"`
	Entries   []string       `json:"entries"`
}

// Notifications (UI-06).

// NoticeStatus is the displayable status of a notice. Visible text is the task
// title and this status only.
type NoticeStatus string

const (
	NoticeNeedsYou           NoticeStatus = "needs_you"
	NoticeVerificationPassed NoticeStatus = "verification_passed"
	NoticeVerificationFailed NoticeStatus = "verification_failed"
	NoticeReadyForReview     NoticeStatus = "ready_for_review"
	NoticeDone               NoticeStatus = "done"
	NoticeFailed             NoticeStatus = "failed"
	NoticeCancelled          NoticeStatus = "cancelled"
)

// NoticeDTO is one notification. There is no body field: nothing but the
// title, the status and navigation/deduplication metadata can be sent.
type NoticeDTO struct {
	ID        core.NoticeID `json:"id"`
	TaskID    core.TaskID   `json:"taskId"`
	TaskTitle string        `json:"taskTitle"`
	Status    NoticeStatus  `json:"status"`
	// Revision is the source revision the notice was made from.
	Revision  int64     `json:"revision"`
	CreatedAt time.Time `json:"createdAt"`
	// Cursor orders history; the client sends the highest it has seen as `after`.
	Cursor int64 `json:"cursor"`
}

// NoticesResponse is the body of GET /api/notifications?after=<cursor>&limit=<n>
// (limit at most 200). With no cursor it returns the newest notices, newest
// first; with a cursor, the notices after it, oldest first. Gap is true when
// history was trimmed past the cursor: the client replaces its list and must
// not replay old browser toasts. Newest is the highest cursor held now.
type NoticesResponse struct {
	Notices []NoticeDTO `json:"notices"`
	Oldest  int64       `json:"oldest"`
	Newest  int64       `json:"newest"`
	Gap     bool        `json:"gap"`
}

// NoticeChangedMessage is the data of a message on TopicNotices. It is sent
// after the commit, carries only IDs and cursors, and tells the client to
// invalidate its history query (or to append when Cursor is the next one).
type NoticeChangedMessage struct {
	NoticeID core.NoticeID `json:"noticeId"`
	Cursor   int64         `json:"cursor"`
}

// Standup (AU-02, UI-03).

// StandupPhase is the result state of a standup read.
type StandupPhase string

const (
	StandupReady   StandupPhase = "ready"
	StandupPartial StandupPhase = "partial"
	StandupFailed  StandupPhase = "failed"
)

// StandupUnavailableDTO labels a source or repo that could not be read.
type StandupUnavailableDTO struct {
	Source string      `json:"source"`
	RepoID core.RepoID `json:"repoId,omitempty"`
	Reason string      `json:"reason"`
}

// StandupCommitDTO, StandupMRDTO and StandupBuildDTO are the typed events.
type StandupCommitDTO struct {
	RepoID   core.RepoID `json:"repoId"`
	RepoName string      `json:"repoName"`
	ID       string      `json:"id"`
	Subject  string      `json:"subject"`
	Author   string      `json:"author"`
	At       time.Time   `json:"at"`
}

type StandupMRDTO struct {
	RepoID   core.RepoID `json:"repoId"`
	RepoName string      `json:"repoName"`
	Number   int         `json:"number"`
	Title    string      `json:"title"`
	State    string      `json:"state"`
	At       time.Time   `json:"at"`
}

type StandupBuildDTO struct {
	RepoID   core.RepoID      `json:"repoId"`
	RepoName string           `json:"repoName"`
	BuildID  core.BuildID     `json:"buildId"`
	Status   core.BuildStatus `json:"status"`
	At       time.Time        `json:"at"`
}

// StandupResponse is the body of GET /api/projects/{id}/standup?from=&to=
// (RFC 3339, at most 31 days). An empty summary is a result, not a failure;
// missing sources are listed in Unavailable. Text is the deterministic
// rendering (at most 64 KiB); the browser copies it, never the server.
type StandupResponse struct {
	ProjectID   core.ProjectID          `json:"projectId"`
	From        time.Time               `json:"from"`
	To          time.Time               `json:"to"`
	Phase       StandupPhase            `json:"phase"`
	Commits     []StandupCommitDTO      `json:"commits"`
	MRs         []StandupMRDTO          `json:"mrs"`
	Builds      []StandupBuildDTO       `json:"builds"`
	Unavailable []StandupUnavailableDTO `json:"unavailable,omitempty"`
	Truncated   []string                `json:"truncated,omitempty"`
	Text        string                  `json:"text"`
	Message     string                  `json:"message,omitempty"`
}

// StandupPolishRequest is the body of POST /api/projects/{id}/standup/polish:
// an explicit user submission that starts one visible Ask task with the
// summary text, through the ordinary action path (the result is an
// ActionResultDTO). A refresh never does this.
type StandupPolishRequest struct {
	RequestID core.RequestID `json:"requestId"`
	From      time.Time      `json:"from"`
	To        time.Time      `json:"to"`
	Agent     string         `json:"agent"`
	Model     string         `json:"model,omitempty"`
}

// New repos and publish (NR-01 to NR-04).

// NewRepoState is the lifecycle state of a new-repo operation.
type NewRepoState string

